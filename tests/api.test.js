import {test,after,before} from 'node:test';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
const dir=mkdtempSync(path.join(tmpdir(),'giftshop-test-'));let child,admin,staff,id;
const port=43000+Math.floor(Math.random()*10000),base=`http://127.0.0.1:${port}`;
async function call(p,method='GET',body,cookie=admin){const r=await fetch(base+'/api/'+p,{method,headers:{'Content-Type':'application/json',...(cookie?{Cookie:cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});return {status:r.status,body:await r.json(),cookie:r.headers.get('set-cookie')?.split(';')[0]};}
before(async()=>{child=spawn(process.execPath,['server.js'],{env:{...process.env,PORT:String(port),DB_PATH:path.join(dir,'test.db'),ADMIN_PASSWORD:'LocalTestPassword2026!'},stdio:['ignore','pipe','pipe']});await new Promise((resolve,reject)=>{const t=setTimeout(()=>reject(Error('Server timeout')),10000);child.stdout.on('data',()=>{clearTimeout(t);resolve();});child.once('exit',code=>{clearTimeout(t);reject(Error('Server exited '+code));});});});
after(async()=>{child?.kill();if(child?.exitCode===null)await new Promise(r=>child.once('exit',r));rmSync(dir,{recursive:true,force:true});});
test('Authentication, authorization, inventory transactions and cancellation',async()=>{
 assert.equal((await call('products','GET',null,'')).status,401);
 assert.equal((await call('login','POST',{username:'admin',password:'wrong'},'')).status,401);
 const login=await call('login','POST',{username:'admin',password:'LocalTestPassword2026!'},'');assert.equal(login.status,200);admin=login.cookie;assert.match(admin,/^session=/);
 assert.equal((await call('users','POST',{username:'staff',password:'StaffPassword2026!',role:'staff'})).status,201);
 staff=(await call('login','POST',{username:'staff',password:'StaffPassword2026!'},'')).cookie;
 assert.equal((await call('products','POST',{sku:'G1',name:'Móc khóa',category:'Quà tặng',price:25000},staff)).status,403);
 id=(await call('products','POST',{sku:'G1',name:'Móc khóa',category:'Quà tặng',price:25000})).body.id;assert.ok(id);
 assert.equal((await call('products','POST',{sku:'G1',name:'Trùng',category:'Quà',price:100})).status,409);
 assert.equal((await call('stock','POST',{product_id:id,qty:-1,note:'Invalid'})).status,400);
 assert.equal((await call('stock','POST',{product_id:id,qty:5,note:'Nhập kiểm thử'})).status,200);
 assert.equal((await call('orders','POST',{items:[{product_id:id,qty:6}]},staff)).status,400);
 assert.equal((await call('products')).body[0].stock,5);
 assert.equal((await call('orders','POST',{items:[{product_id:id,qty:1},{product_id:id,qty:1}]})).status,400);
 const results=await Promise.all([call('orders','POST',{items:[{product_id:id,qty:4}]},staff),call('orders','POST',{items:[{product_id:id,qty:4}]},staff)]);
 assert.deepEqual(results.map(r=>r.status).sort(),[201,400]);
 const order=results.find(r=>r.status===201).body.id;
 assert.equal((await call('products')).body[0].stock,1);
 assert.equal((await call('stats')).body.revenue,100000);
 assert.equal((await call('stats','GET',null,staff)).status,403);
 assert.equal((await call(`orders/${order}/cancel`,'POST',{},staff)).status,403);
 assert.equal((await call(`orders/${order}/cancel`,'POST',{})).status,200);
 assert.equal((await call(`orders/${order}/cancel`,'POST',{})).status,400);
 assert.equal((await call('products')).body[0].stock,5);
 assert.equal((await call('stats')).body.revenue,0);
 const csrf=await fetch(base+'/api/orders',{method:'POST',headers:{Cookie:admin,Origin:'https://untrusted.example','Content-Type':'application/json'},body:'{}'});assert.equal(csrf.status,403);
 assert.equal((await call('logout','POST',{})).status,200);assert.equal((await call('products')).status,401);
});
